/**
 * `cowait report`: what Claude changed and how much of it a human actually read, over the last
 * N days. A self-contained light HTML page (or Markdown) you can keep or show your team.
 */
import path from 'node:path';
import { emptyDay, localDay, type DayStat, type State } from './engine/state.js';
import { levelInfo } from './engine/progress.js';
import type { Lang } from './i18n.js';

export interface ProjectRow {
  name: string;
  dir: string;
  turns: number;
  files: number;
  read: number;
  flagged: number;
  unread: number;
  pending: number;
}

export interface ReportData {
  from: string;
  to: string;
  days: (DayStat & { day: string })[];
  turns: number;
  files: number;
  read: number;
  flagged: number;
  notes: number;
  learned: number;
  activeDays: number;
  coverage: number | null;
  projects: ProjectRow[];
  level: number;
  bestStreak: number;
}

export function buildReport(s: State, days: number, now = Date.now()): ReportData {
  const list: (DayStat & { day: string })[] = [];
  const end = new Date(now);
  for (let i = days - 1; i >= 0; i--) {
    const day = localDay(new Date(end.getFullYear(), end.getMonth(), end.getDate() - i, 12).getTime());
    list.push({ ...emptyDay(), ...(s.days[day] ?? {}), day });
  }
  const sum = (f: (d: DayStat) => number) => list.reduce((n, d) => n + f(d), 0);
  const from = list[0].day;
  const fromTs = new Date(`${from}T00:00:00`).getTime();

  const byDir = new Map<string, ProjectRow>();
  const row = (dir: string) => {
    let r = byDir.get(dir);
    if (!r) {
      r = { name: path.basename(dir.replace(/\\/g, '/')) || dir, dir, turns: 0, files: 0, read: 0, flagged: 0, unread: 0, pending: 0 };
      byDir.set(dir, r);
    }
    return r;
  };
  for (const m of s.turns) if (m.start >= fromTs && m.files > 0) row(m.cwd).turns++;
  for (const c of s.review) {
    if (c.t < fromTs) continue;
    const r = row(c.cwd);
    r.files++;
    if (c.status === 'ok' && !c.quick) r.read++;
    else if (c.status === 'flag') {
      r.read++;
      r.flagged++;
    } else if (c.status === 'new') r.pending++;
    else r.unread++;
  }
  const files = sum((d) => d.files);
  const read = sum((d) => d.reviewed + d.flagged);
  return {
    from,
    to: list[list.length - 1].day,
    days: list,
    turns: sum((d) => d.turns),
    files,
    read,
    flagged: sum((d) => d.flagged),
    notes: sum((d) => d.notes),
    learned: sum((d) => d.learned),
    activeDays: list.filter((d) => d.reviewed + d.flagged >= 1 || d.learned >= 5 || d.puzzle > 0).length,
    coverage: files > 0 ? Math.min(1, read / files) : null,
    projects: [...byDir.values()].filter((p) => p.files > 0).sort((a, b) => b.files - a.files),
    level: levelInfo(s.xp).level,
    bestStreak: s.bestStreak,
  };
}

const pct = (x: number | null) => (x === null ? '—' : `${Math.round(x * 100)}%`);

